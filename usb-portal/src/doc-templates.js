// Шаблоны документов. Разметка тела шаблона (по строкам):
//   ^ текст — по центру, > текст — по правому краю, < текст — по левому краю без отступа,
//   # текст — заголовок (крупно, жирно, по центру), обычная строка — абзац по ширине с отступом,
//   «левое | центр | правое» — строка из колонок, пустая строка — интервал,
//   ~ в начале строки — мелкий шрифт (12 pt), сочетается с выравниванием: «~^текст».
// Служебные строки: «::: поля 10 10 10 10» — поля листа в мм (верх, право, низ, лево);
//   «::: колонки 47/16/37» … «:::» … «::: конец» — блок колонок (ширины в %), «::: по центру» / «::: снизу»
//   начинают следующую колонку с выравниванием по вертикали.
// Внутри строк: **жирный**, __курсив__, {Поле} — заполняет сотрудник, [дата] — ставится автоматически
// (формат берётся из примера в скобках), [подпись] — подпись автора из профиля, [печать] — печать УВД,
// [герб] или [герб 32мм] — геральдический знак МВД (обычно отдельной строкой «^[герб]» в начале документа).

const TOKEN_RE = /\{([^{}\n]+)\}|\[([^[\]\n]+)\]/g;
const isImageToken = (inner) => inner === 'печать' || /^герб(?:\s+\d+(?:[.,]\d+)?\s*мм)?$/.test(inner);

/** Поля, количество дат и нужна ли подпись — для проверки отправленного документа на сервере. */
export function parseTemplate(body) {
  const fields = [];
  let dates = 0;
  let signature = false;
  for (const m of body.matchAll(TOKEN_RE)) {
    if (m[1] !== undefined) {
      const key = m[1].trim();
      if (key && !fields.includes(key)) fields.push(key);
    } else {
      const inner = m[2].trim().toLowerCase();
      if (inner === 'подпись') signature = true;
      else if (!isImageToken(inner)) dates += 1;
    }
  }
  return { fields, dates, signature };
}

